import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { inflateSync } from 'node:zlib';

export const MAGIC = Buffer.from('DCFC0001', 'ascii');
export const PACK_SCHEMA = 'dc-favicon-pack-v1';
export const CATALOGUE_SCHEMA = 'dc-favicon-catalogue-v1';
export const IMAGE_COUNT = 4 * 7 * 21;
export const MAX_PACK_BYTES = 128 * 1024 * 1024;
export const MAX_HEADER_BYTES = 3 * 1024 * 1024;
export const MAX_PNG_BYTES = 2 * 1024 * 1024;
export const MAX_VARIANTS = 8;
const HEX256 = /^[0-9a-f]{64}$/;
const HEX40 = /^[0-9a-f]{40}$/;
const PNG_SIGNATURE = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]);

/** Return the SHA-256 digest of exact binary bytes.
 * @param {Uint8Array} bytes - Original or generated bytes.
 * @returns {string} Lowercase hexadecimal digest.
 */
export function sha256(bytes) {
  return createHash('sha256').update(bytes).digest('hex');
}

/** Recursively serialize data as canonical UTF-8 JSON.
 * @param {unknown} value - JSON-compatible data.
 * @returns {string} Whitespace-free, recursively key-sorted JSON.
 */
export function canonicalJson(value) {
  if (Array.isArray(value)) return '[' + value.map(canonicalJson).join(',') + ']';
  if (value !== null && typeof value === 'object') {
    return '{' + Object.keys(value).sort().map(key =>
      JSON.stringify(key) + ':' + canonicalJson(value[key])).join(',') + '}';
  }
  const encoded = JSON.stringify(value);
  assert(encoded !== undefined, 'Non-JSON value');
  return encoded;
}

/** Parse a numeric DC triplet without ordering development suffixes.
 * @param {string} value - DC release or issue-qualified version.
 * @returns {number[]} Safe integer major/minor/patch components.
 */
export function versionTriplet(value) {
  assert(typeof value === 'string', 'Version must be a string');
  const match = /^(\d+)\.(\d+)\.(\d+)(?:-[A-Za-z0-9][A-Za-z0-9.-]*)?$/.exec(value);
  assert(match, 'Invalid numeric major.minor.patch version');
  const parts = match.slice(1, 4).map(Number);
  assert(parts.every(Number.isSafeInteger), 'Unsafe version integer');
  return parts;
}

/** Choose the latest numerical minimum compatible catalogue boundary.
 * @param {object} catalogue - Complete V1 catalogue.
 * @param {string} runningVersion - DC version, optional ignored suffix.
 * @returns {object|null} Matching dataset, or null.
 */
export function selectDataset(catalogue, runningVersion) {
  assert(catalogue?.schema === CATALOGUE_SCHEMA &&
    Object.keys(catalogue).sort().join(',') === 'datasets,schema',
    'Catalogue schema/fields mismatch');
  assert(Array.isArray(catalogue.datasets) && catalogue.datasets.length <= 256,
    'Catalogue count invalid');
  const wanted = versionTriplet(runningVersion);
  const seen = new Set();
  let chosen = null;
  let chosenParts = null;
  for (const dataset of catalogue.datasets) {
    assert(dataset && Object.keys(dataset).sort().join(',') ===
      'favicons,update_every_ms,version', 'Unexpected catalogue dataset fields');
    const v = versionTriplet(dataset.version);
    const key = v.join('.');
    assert(!seen.has(key), 'Duplicate normalized dataset boundary');
    seen.add(key);
    assert(dataset.version === key, 'Catalogue boundaries must be normalized');
    assert(Number.isSafeInteger(dataset.update_every_ms) && dataset.update_every_ms > 0,
      'Invalid update interval');
    const asset = dataset.favicons;
    assert(asset && Object.keys(asset).sort().join(',') ===
      'bytes,commit,path,sha256', 'Unexpected asset fields');
    assert(asset && HEX40.test(asset.commit) &&
      typeof asset.path === 'string' &&
      /^assets\/favicons\/v1\/[a-z0-9-]+\.dcfav$/.test(asset.path) &&
      Number.isSafeInteger(asset.bytes) && asset.bytes > 12 &&
      asset.bytes <= MAX_PACK_BYTES && HEX256.test(asset.sha256),
      'Invalid immutable pack metadata');
    if (compareTriplets(v, wanted) <= 0 &&
      (!chosenParts || compareTriplets(v, chosenParts) > 0)) {
      chosen = dataset;
      chosenParts = v;
    }
  }
  return chosen;
}

/** Compare numeric triplets, not textual versions.
 * @param {number[]} a - Left numeric triplet.
 * @param {number[]} b - Right numeric triplet.
 * @returns {number} Signed comparison result.
 */
export function compareTriplets(a, b) {
  for (let i = 0; i < 3; i++) if (a[i] !== b[i]) return a[i] < b[i] ? -1 : 1;
  return 0;
}

/** Check PNG framing, per-chunk CRC, decoded colour format and exact size.
 * @param {Uint8Array} input - Complete PNG bytes.
 * @returns {{width:number,height:number}} Validated dimensions.
 */
export function validatePng(input) {
  const bytes = Buffer.from(input);
  assert(bytes.length >= 45 && bytes.length <= MAX_PNG_BYTES, 'PNG byte bound');
  assert(bytes.subarray(0, 8).equals(PNG_SIGNATURE), 'PNG signature');
  let p = 8, width = 0, height = 0, first = true, end = false;
  let idat = 0;
  while (p < bytes.length) {
    assert(p + 12 <= bytes.length, 'Truncated PNG chunk header');
    const length = bytes.readUInt32BE(p);
    assert(length <= MAX_PNG_BYTES && p + 12 + length <= bytes.length,
      'PNG chunk exceeds buffer');
    const type = bytes.toString('ascii', p + 4, p + 8);
    const crc = bytes.readUInt32BE(p + 8 + length);
    assert(crc32(bytes.subarray(p + 4, p + 8 + length)) === crc, 'PNG CRC error');
    if (first) {
      assert(type === 'IHDR' && length === 13, 'PNG IHDR must be first');
      width = bytes.readUInt32BE(p + 8);
      height = bytes.readUInt32BE(p + 12);
      assert(width > 0 && height > 0 && width <= 512 && height <= 512,
        'Invalid PNG dimensions');
      assert(bytes[p + 16] === 8 && [2, 6].includes(bytes[p + 17]) &&
        bytes[p + 18] === 0 && bytes[p + 19] === 0 && bytes[p + 20] === 0,
        'Only 8-bit noninterlaced RGB/RGBA PNG is supported');
    }
    if (type === 'IDAT') idat++;
    if (type === 'IEND') {
      assert(length === 0 && p + 12 === bytes.length, 'Trailing PNG data');
      end = true;
    }
    p += 12 + length;
    first = false;
  }
  assert(end && idat > 0, 'PNG IDAT/IEND missing');
  // Decode IDAT stream to reject a PNG with valid framing but corrupt pixels.
  p = 8;
  const streams = [];
  while (p < bytes.length) {
    const length = bytes.readUInt32BE(p);
    const type = bytes.toString('ascii', p + 4, p + 8);
    if (type === 'IDAT') streams.push(bytes.subarray(p + 8, p + 8 + length));
    p += 12 + length;
  }
  const components = bytes[25] === 6 ? 4 : 3;
  const stride = width * components + 1;
  const expected = stride * height;
  const inflated = inflateSync(Buffer.concat(streams), { maxOutputLength: expected + 1 });
  assert(inflated.length === expected, 'PNG decoded length mismatch');
  for (let y = 0; y < height; y++) {
    assert(inflated[y * stride] <= 4, 'Invalid PNG filter method');
  }
  return { width, height };
}

/** Compute the standard IEEE CRC-32 of PNG chunk bytes.
 * @param {Uint8Array} data - Bytes starting with chunk type.
 * @returns {number} Unsigned CRC-32.
 */
export function crc32(data) {
  let crc = 0xffffffff;
  for (const byte of data) {
    crc ^= byte;
    for (let j = 0; j < 8; j++) {
      crc = (crc >>> 1) ^ ((crc & 1) ? 0xedb88320 : 0);
    }
  }
  return (crc ^ 0xffffffff) >>> 0;
}

/** Build the exact indexed V1 format from externally rendered PNG bytes.
 * @param {object[]} variants - Source provenance and 4x7x21 PNG arrays.
 * @returns {Buffer} Deterministic binary pack.
 */
export function encodePack(variants) {
  assert(Array.isArray(variants) && variants.length > 0 &&
    variants.length <= MAX_VARIANTS, 'Variant count out of range');
  const spans = [], payload = [], seen = new Set();
  let offset = 0;
  for (let v = 0; v < variants.length; v++) {
    const item = variants[v];
    assert(HEX256.test(item.source_sha256), 'Source SHA-256 invalid');
    assert(!seen.has(item.source_sha256), 'Duplicate source resource digest');
    seen.add(item.source_sha256);
    assert(item.id === String(v), 'Variant ids must be contiguous');
    const images = [];
    assert(Array.isArray(item.pngs) && item.pngs.length === IMAGE_COUNT,
      'Exactly 588 PNGs per variant');
    for (let base = 0; base < 4; base++) {
      const pies = [];
      for (let step = 0; step < 7; step++) {
        const pulses = [];
        for (let frame = 0; frame < 21; frame++) {
          const png = Buffer.from(item.pngs[(base * 7 + step) * 21 + frame]);
          const dims = validatePng(png);
          assert(dims.width === item.width && dims.height === item.height,
            'Source/output image dimensions mismatch');
          assert(offset + png.length <= MAX_PACK_BYTES, 'Pack payload too large');
          pulses.push({ offset, bytes: png.length });
          payload.push(png);
          offset += png.length;
        }
        pies.push(pulses);
      }
      images.push(pies);
    }
    spans.push({
      id: item.id, source_sha256: item.source_sha256,
      width: item.width, height: item.height, images
    });
  }
  const manifest = Buffer.from(canonicalJson({ schema: PACK_SCHEMA, variants: spans }));
  assert(manifest.length <= MAX_HEADER_BYTES, 'Pack JSON header too large');
  const prefix = Buffer.alloc(12);
  MAGIC.copy(prefix);
  prefix.writeUInt32LE(manifest.length, 8);
  const pack = Buffer.concat([prefix, manifest, ...payload]);
  assert(pack.length <= MAX_PACK_BYTES, 'Total pack byte bound');
  return pack;
}

/** Validate canonical manifest, nonoverlapping payload and every PNG.
 * @param {Uint8Array} input - Untrusted pack bytes.
 * @returns {object} Parsed V1 manifest.
 */
export function validatePack(input) {
  const pack = Buffer.from(input);
  assert(pack.length >= 12 && pack.length <= MAX_PACK_BYTES, 'Pack bounds');
  assert(pack.subarray(0, 8).equals(MAGIC), 'Pack magic mismatch');
  const length = pack.readUInt32LE(8);
  assert(length > 0 && length <= MAX_HEADER_BYTES &&
    length + 12 <= pack.length, 'Manifest bounds');
  const json = pack.toString('utf8', 12, 12 + length);
  const manifest = JSON.parse(json);
  assert(json === canonicalJson(manifest), 'Manifest must be canonical JSON');
  assert(Object.keys(manifest).sort().join(',') === 'schema,variants',
    'Unexpected manifest fields');
  assert(manifest.schema === PACK_SCHEMA && Array.isArray(manifest.variants) &&
    manifest.variants.length > 0 && manifest.variants.length <= MAX_VARIANTS,
    'Pack schema/variants invalid');
  const payloadOffset = 12 + length;
  const ranges = [];
  const sources = new Set();
  for (let n = 0; n < manifest.variants.length; n++) {
    const variant = manifest.variants[n];
    assert(variant && Object.keys(variant).sort().join(',') ===
      'height,id,images,source_sha256,width', 'Unexpected variant fields');
    assert(variant.id === String(n) && HEX256.test(variant.source_sha256) &&
      !sources.has(variant.source_sha256) &&
      Number.isInteger(variant.width) && variant.width > 0 && variant.width <= 512 &&
      Number.isInteger(variant.height) && variant.height > 0 && variant.height <= 512,
      'Variant provenance/dimensions invalid');
    sources.add(variant.source_sha256);
    assert(Array.isArray(variant.images) && variant.images.length === 4,
      'Base state dimension');
    for (const pies of variant.images) {
      assert(Array.isArray(pies) && pies.length === 7, 'Pie step dimension');
      for (const frames of pies) {
        assert(Array.isArray(frames) && frames.length === 21, 'Pulse dimension');
        for (const image of frames) {
          assert(Object.keys(image).sort().join(',') === 'bytes,offset' &&
            Number.isSafeInteger(image.offset) && image.offset >= 0 &&
            Number.isSafeInteger(image.bytes) && image.bytes >= 45 &&
            image.bytes <= MAX_PNG_BYTES, 'PNG index bounds');
          const start = payloadOffset + image.offset;
          const end = start + image.bytes;
          assert(end <= pack.length, 'Indexed PNG outside payload');
          const png = pack.subarray(start, end);
          const dims = validatePng(png);
          assert(dims.width === variant.width && dims.height === variant.height,
            'PNG dimensions do not match variant');
          ranges.push([start, end]);
        }
      }
    }
  }
  ranges.sort((a, b) => a[0] - b[0]);
  let next = payloadOffset;
  for (const [start, end] of ranges) {
    assert(start === next, 'PNG spans overlap or leave uncovered bytes');
    next = end;
  }
  assert(next === pack.length, 'Unindexed pack tail');
  return manifest;
}
